def related_terms(query: str, limit: int = 2) -> list[str]:
    """返回可作为补充检索词的同义词/上位词，取不到返回空列表。

    优先查同义词表；查不到时，若该词命中某个行业的品类关键词，
    就用行业名（如「螺丝」→「五金配件」）作为上位词补一条。
    """
    q = (query or "").strip()
    if not q:
        return []
    out: list[str] = []
    for term in SYNONYMS.get(q, ()):
        if term != q and term not in out:
            out.append(term)
    if len(out) < limit:
        industry = infer_industry(q)
        if industry and industry not in out and industry != q:
            out.append(industry)
    return out[:limit]
