def belt_of(city: str) -> dict | None:
    """按城市名查产业带；自动去掉「市/区/县」后缀，支持「浙江宁波」这类前缀。"""
    if not city:
        return None
    key = str(city).strip()
    for suffix in ("市", "区", "县", "自治州"):
        if key.endswith(suffix):
            key = key[: -len(suffix)]
    if key in BELTS:
        return BELTS[key]
    # 地址串里包含产业带城市名（如「浙江省宁波市北仑区」）
    for name, belt in BELTS.items():
        if name and name in city:
            return belt
    return None


def belt_bonus(industry: str, belt: dict | None) -> int:
    """产业带品类与目标行业匹配时给相关度加分。"""
    if not belt or not industry:
        return 0
    return 2 if industry in (belt.get("categories") or []) else 0


