# 判断「生产型厂家」的经营范围动词。命中任一即为生产型 —— 采购要的是能开模量产的人，
# 不是只做批发的贸易公司。
_MANUFACTURE_WORDS = ("制造", "生产", "加工", "产销", "制作", "组装", "锻造",
                      "铸造", "冶炼", "纺织", "缝制", "印刷")

# 判断出口资质
_EXPORT_WORDS = ("进出口", "货物进出口", "技术进出口", "对外贸易")

# 提取产品词时需要剥离的行业后缀/修饰词
_PRODUCT_NOISE = re.compile(
    r"(产品的?)?(生产|制造|加工|销售|批发|零售|研发|设计|技术开发|技术服务|销售及|"
    r"生产及|及销售|及|和|等)+$"
)
# 经营范围条目的前置动词/套话（「增加：从事…」「依法须经批准…」）
_LEAD_NOISE = re.compile(
    r"^(增加|变更|从事|自营|代理|依法|须经|经批准|许可|一般项目|许可项目|涉及|"
    r"主要包括|包括|上述|其他|以及|及其|和)+[：:，,]?"
)
# 经营范围里的纯业务描述，不构成「产品」
_NON_PRODUCT = re.compile(
    r"(货物|技术)?(进出口|代理)$|^(国内)?贸易$|企业管理|信息咨询|技术服务|"
    r"技术开发|市场营销|会议|展览|广告|仓储|物流|运输|投资|咨询|服务|"
    r"国家|依法|不得|须经|凭|项目|范围|批准|经营"
)


def _clean_product(item: str) -> str:
    """去掉一个经营范围条目里的套话与行业后缀，留下品类词。"""
    text = item
    for _ in range(3):
        new = _LEAD_NOISE.sub("", text).strip()
        new = _PRODUCT_NOISE.sub("", new).strip()
        if new == text:
            break
        text = new
    return text


def _split_scope(scope: str) -> list[str]:
    """经营范围按中英文分号/冒号/逗号/顿号切分成条目。"""
    if not scope:
        return []
    parts = re.split(r"[;；:：,，、\n]", scope)
    return [p.strip() for p in parts if p.strip()]


def infer_industry(scope: str) -> str:
    """从经营范围推断行业，无法判断时返回空串（前端显示为「工商企业」）。"""
    text = scope or ""
    for industry, words in INDUSTRY_RULES:
        if any(w in text for w in words):
            return industry
    return ""


def extract_products(scope: str, limit: int = 8) -> list[str]:
    """从经营范围里提取「能生产什么」，返回干净的品类词列表。

    做法：按分号切条目 → 去掉「制造/销售」等后缀 → 剔除纯业务描述 → 去重。
    """
    out: list[str] = []
    for item in _split_scope(scope):
        if len(item) > 24:
            continue
        cleaned = _clean_product(item)
        # 品类词应当短小；过长说明仍是描述性语句，丢弃
        if len(cleaned) < 2 or len(cleaned) > 10:
            continue
        if _NON_PRODUCT.search(cleaned) or cleaned in out:
            continue
        out.append(cleaned)
        if len(out) >= limit:
            break
    return out


def is_manufacturer(scope: str) -> bool:
    """经营范围含生产制造类动词 → 生产型厂家。"""
    return any(w in (scope or "") for w in _MANUFACTURE_WORDS)


def can_export(scope: str) -> bool:
    """经营范围含进出口资质 → 具备自营出口能力。"""
    return any(w in (scope or "") for w in _EXPORT_WORDS)


# ---------------------------------------------------------------------------
# 注册资本 → 规模档位
# 工商数据没有员工数/厂房面积/年销售额，注册资本是唯一可得的规模代理指标。
# 必须把口径明确写出来（scale_basis），不能伪装成员工数。
# ---------------------------------------------------------------------------
_CAPITAL_RE = re.compile(r"([\d.]+)\s*(亿|万|千万|百万)?")


def capital_to_wan(capital_text: str) -> float | None:
    """把「5000万人民币」/「1.2亿」这类文本换算成「万元」数值。"""
    if not capital_text:
        return None
    m = _CAPITAL_RE.search(str(capital_text).replace(",", ""))
    if not m:
        return None
    try:
        num = float(m.group(1))
    except ValueError:
        return None
    unit = m.group(2) or ""
    if unit == "亿":
        num *= 10000
    elif unit in ("千万",):
        num *= 1000
    elif unit in ("百万",):
        num *= 100
    elif unit == "万":
        pass
    elif unit == "":
        # 无单位按「元」处理（注册资本通常带「万」，无单位的情况极少）
        num /= 10000
    return round(num, 2)


def scale_from_capital(capital_text: str) -> tuple[str, str]:
    """返回 (规模档位, 口径说明)。无法解析时返回 ("", "")。"""
    wan = capital_to_wan(capital_text)
    if wan is None:
        return "", ""
    if wan < 100:
        label = "小型"
    elif wan < 1000:
        label = "中型"
    else:
        label = "大型"
    return label, f"注册资本 {capital_text}"


